"""EDP-04 (BI-PF-1296): data-plane threat register - validate + render.

SSOT: ``config/data-plane-threats.json`` (the six EDP data-plane threat categories -> source -> sink ->
flows -> control -> owner -> evidence). Renders ``docs/EDP-DATA-PLANE-THREAT-MODEL.md``.

Fail-closed: FAILS when a required category is missing, a row is incomplete, an ``owner``/``evidence``
does not resolve (repo path, ``gate:<precheck-gate>`` or ``item:<BI-PF-id>``), an ADR reference is not in
the decision ledger, or the rendered doc is stale. Wired into precheck as gate ``data-plane-threats``.
"""
import argparse
import json
import os
import re
import sys

try:
    from core.paths import ROOT as _ROOT
except ImportError:
    _ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
if _ROOT not in sys.path:
    sys.path.insert(0, _ROOT)

REG = os.path.join(_ROOT, "config", "data-plane-threats.json")
OUT = os.path.join(_ROOT, "docs", "EDP-DATA-PLANE-THREAT-MODEL.md")
ADRS = os.path.join(_ROOT, "docs", "ARCHITECTURE-DECISIONS.md")
_REQUIRED = ("cross-tenant-idor", "path-traversal", "token-role-spoofing",
             "object-url-leakage", "egress", "residency-bypass")
_STATUS = ("implemented", "partial", "planned")
_ITEM_ID = re.compile(r"^BI-[A-Z]+-\d+$")


def _load() -> dict:
    with open(REG, encoding="utf-8") as f:
        return json.load(f)


def _gate_names() -> set:
    names = set()
    try:
        for ln in open(os.path.join(_ROOT, "scripts", "dev", "precheck.py"), encoding="utf-8"):
            m = re.match(r'\s*\(\s*"([a-z0-9\-]+)"\s*,', ln)
            if m:
                names.add(m.group(1))
    except Exception:
        pass
    return names


def _adr_ledger() -> str:
    try:
        return open(ADRS, encoding="utf-8").read()
    except Exception:
        return ""


def _owner_ok(owner: str) -> bool:
    return bool(owner) and (os.path.exists(os.path.join(_ROOT, owner)) or bool(_ITEM_ID.match(owner)))


def _evidence_ok(ev: str, gates) -> bool:
    if not ev:
        return False
    if ev.startswith("gate:"):
        return ev.split(":", 1)[1] in gates
    if ev.startswith("item:"):
        return bool(ev.split(":", 1)[1])
    return os.path.exists(os.path.join(_ROOT, ev))


def validate(reg: dict) -> list:
    probs, gates, ledger = [], _gate_names(), _adr_ledger()
    if not isinstance(reg.get("version"), int) or reg.get("version", 0) < 1:
        probs.append("missing/invalid 'version' (must be an int >= 1)")
    threats = reg.get("threats") or []
    seen = [t.get("id") for t in threats]
    for req in _REQUIRED:
        if req not in seen:
            probs.append(f"missing required threat category: {req}")
    for t in threats:
        tid = t.get("id") or "?"
        for field in ("id", "title", "source", "sink", "control", "owner", "evidence",
                      "status", "adr", "mitigation_item"):
            if not t.get(field):
                probs.append(f"{tid}: missing '{field}'")
        if not isinstance(t.get("flows"), list) or not t.get("flows"):
            probs.append(f"{tid}: 'flows' must be a non-empty list")
        if t.get("status") not in _STATUS:
            probs.append(f"{tid}: invalid status {t.get('status')!r}")
        if not _owner_ok(t.get("owner", "")):
            probs.append(f"{tid}: owner does not resolve ({t.get('owner')!r})")
        ev = t.get("evidence", "")
        if t.get("status") in ("implemented", "partial") and not _evidence_ok(ev, gates):
            probs.append(f"{tid}: status={t.get('status')} but evidence does not resolve ({ev!r})")
        if t.get("status") == "planned" and not (ev.startswith("item:") or ev.startswith("gate:")):
            probs.append(f"{tid}: planned evidence must be 'item:<id>' or 'gate:<name>' ({ev!r})")
        for a in (t.get("adr") or []):
            if a not in ledger:
                probs.append(f"{tid}: ADR reference {a!r} not found in docs/ARCHITECTURE-DECISIONS.md")
    return probs


def render(reg: dict) -> str:
    lines = ["# EDP Data-Plane Threat Model (generated)", "",
             "> Generated by `scripts/dev/data_plane_threat_check.py` from `config/data-plane-threats.json`.",
             "> **Do not edit by hand.** The register is the SSOT (BI-PF-1296 / EDP-04); findings cite the",
             "> decision ledger (`docs/ARCHITECTURE-DECISIONS.md`). status: implemented | partial | planned.", "",
             f"Register version: **{reg.get('version')}**", "",
             "| Threat | Source -> Sink | Control | Owner | Status | Evidence | ADR |",
             "|---|---|---|---|---|---|---|"]
    for t in reg.get("threats") or []:
        flow = f"{t.get('source')} -> {t.get('sink')}"
        lines.append(f"| **{t.get('id')}** - {t.get('title')} | {flow} | {t.get('control')} | "
                     f"`{t.get('owner')}` | {t.get('status')} | `{t.get('evidence')}` | "
                     f"{', '.join(t.get('adr') or [])} |")
    lines += ["", "## Mitigation ownership", "",
              "Each category is mitigated by the owning item listed above (implementation is out of scope for",
              "EDP-04; it is tracked/delivered by EDP-07..16). EDP-04 owns the register + this model, not the",
              "mitigations.", ""]
    return "\n".join(lines)


def _current() -> str:
    try:
        return open(OUT, encoding="utf-8").read()
    except Exception:
        return ""


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args(argv)
    reg = _load()
    probs = validate(reg)
    if probs:
        print(f"data-plane-threats: FAIL ({len(probs)} problem(s))")
        for p in probs[:20]:
            print("   -", p)
        return 1
    doc = render(reg)
    if a.write:
        with open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(doc)
        print(f"data-plane-threats: wrote {os.path.relpath(OUT, _ROOT)}")
        return 0
    if a.check and doc.strip() != _current().strip():
        print("data-plane-threats: FAIL - docs/EDP-DATA-PLANE-THREAT-MODEL.md stale; run: "
              "python scripts/dev/data_plane_threat_check.py --write")
        return 1
    n = len(reg.get("threats") or [])
    planned = sum(1 for t in (reg.get("threats") or []) if t.get("status") == "planned")
    print(f"data-plane-threats: OK ({n} categories covered; {planned} planned -> see "
          f"docs/EDP-DATA-PLANE-THREAT-MODEL.md)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
