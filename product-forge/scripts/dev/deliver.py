#!/usr/bin/env python3
"""BI-PF-0421 / BI-PF-1549: Delivery runner.

Supports two delivery lanes:
1. Plane A (local developer / AI session): ``python scripts/dev/deliver.py --item <ID>``.
   Automates all post-Gate 2 delivery operations in under 30 seconds:
   - Auto-bundles AC verification, DoD evidence, and final report.
   - Commits Gate 2.5 review evidence and backlog updates separately (pre-commit compliant).
   - Auto-commits docs index if regenerated by git hooks.
   - Runs pre-merge verification (sync_develop.py + wired_audit.py).
   - Switches to develop, executes controlled merge (--no-ff), and pushes to origin/develop.
   - Records delivery provenance (links.delivery) in backlog DB and disk mirror.
   - Cleans up merged local feature branch.

2. Plane B (background queue): ``python scripts/dev/deliver.py [--scope S] [--project P] [--limit N]``.
   Drains items in status ``verifying`` via optimistic delivery lane.
"""
from __future__ import annotations

import argparse
import glob
import json
import os
import subprocess
import sys
from pathlib import Path

try:
    from core.paths import ROOT as _ROOT
except ImportError:
    _ROOT = Path(__file__).resolve().parents[2]

for _p in (str(_ROOT), str(Path(_ROOT) / "scripts" / "dev")):
    if _p not in sys.path:
        sys.path.insert(0, _p)


def _run_cmd(cmd: list[str], cwd: Path | str = _ROOT, check: bool = True) -> subprocess.CompletedProcess[str]:
    res = subprocess.run(cmd, cwd=str(cwd), capture_output=True, text=True)
    if check and res.returncode != 0:
        err = (res.stderr or res.stdout or "").strip()
        raise RuntimeError(f"Command failed ({' '.join(cmd)}): {err}")
    return res


def deliver_plane_a(item_id: str, scope: str = "product_forge", project: str | None = None,
                    push: bool = True, delete_branch: bool = True) -> dict:
    """Execute complete, hook-compliant delivery for a completed Plane A work item."""
    from core import backlog
    import finalize_item

    # 1. Determine active branch
    cur_branch = _run_cmd(["git", "branch", "--show-current"]).stdout.strip()
    if cur_branch in ("develop", "main", "master"):
        raise RuntimeError(f"Cannot deliver from integration branch '{cur_branch}'. Switch to your feature branch first.")

    print(f"[Deliver] Starting Plane A delivery for {item_id} (branch={cur_branch})...")
    it = backlog.get_epic(scope, project, item_id)
    if not it:
        raise RuntimeError(f"Item not found: {item_id} (scope={scope})")

    # 2. Auto-bundle item finalization if not already completed
    print(f"[Deliver] Auto-bundling AC verification, DoD, and final report on {item_id}...")
    finalize_item.auto_bundle(item_id, scope=scope, project=project)
    rep = finalize_item.build(item_id)
    if rep.get("ac_problems") or rep.get("disposition_problems"):
        raise RuntimeError(f"Finalize problems for {item_id}: {rep.get('ac_problems')} {rep.get('disposition_problems')}")
    it = backlog.update(scope, project, item_id, final_report=rep, status="completed",
                        _note="Plane A deliver: final report persisted and status completed")

    # 3. Export item JSON to disk mirror so git sees clean state
    item_json_path = Path(_ROOT) / "data" / "backlog" / "items" / f"{item_id}.json"
    if item_json_path.parent.exists():
        with open(item_json_path, "w", encoding="utf-8") as f:
            f.write(json.dumps(it, indent=2, ensure_ascii=False) + "\n")

    # 4. Commit review evidence separately (comply with pre-commit hook)
    rev_pattern = str(Path(_ROOT) / "engineering" / "reviews" / f"{item_id}-*.json")
    rev_files = [f for f in glob.glob(rev_pattern) if os.path.isfile(f)]
    for rf in rev_files:
        status = _run_cmd(["git", "status", "--porcelain", rf]).stdout.strip()
        if status:
            print(f"[Deliver] Committing review evidence: {Path(rf).name}...")
            _run_cmd(["git", "add", rf])
            _run_cmd(["git", "commit", "-m", f"docs(review): record Gate 2.5 delivery review evidence for {item_id}"])

    # 5. Commit backlog bookkeeping separately (comply with pre-commit hook)
    backlog_status = _run_cmd(["git", "status", "--porcelain", "data/backlog/"]).stdout.strip()
    if backlog_status:
        print("[Deliver] Committing backlog completion bookkeeping...")
        _run_cmd(["git", "add", "data/backlog/"])
        _run_cmd(["git", "commit", "-m", f"docs(backlog): complete {item_id} with AC verification and DoD evidence"])

    # 6. Auto-commit regenerated docs index if touched by pre-commit hook
    docs_status = _run_cmd(["git", "status", "--porcelain", "docs/README.md"]).stdout.strip()
    if docs_status:
        print("[Deliver] Committing updated docs index...")
        _run_cmd(["git", "add", "docs/README.md"])
        _run_cmd(["git", "commit", "-m", f"docs({item_id}): update docs index"])

    # 7. Pre-merge verification (sync develop + wired audit)
    print("[Deliver] Running pre-merge verification (sync_develop & wired_audit)...")
    sync_res = _run_cmd([sys.executable, str(Path(_ROOT) / "scripts" / "dev" / "sync_develop.py")], check=False)
    if sync_res.returncode != 0:
        raise RuntimeError(f"sync_develop failed: {sync_res.stderr or sync_res.stdout}")

    audit_res = _run_cmd([sys.executable, str(Path(_ROOT) / "scripts" / "dev" / "wired_audit.py")], check=False)
    if audit_res.returncode != 0:
        raise RuntimeError(f"wired_audit failed: {audit_res.stderr or audit_res.stdout}")

    # 8. Controlled merge into develop
    target_branch = "develop"
    print(f"[Deliver] Switching to {target_branch} and merging {cur_branch} (--no-ff)...")
    _run_cmd(["git", "checkout", target_branch])
    title = str(it.get("title") or item_id)
    merge_msg = f"feat: merge {item_id} {title}"
    _run_cmd(["git", "merge", "--no-ff", cur_branch, "-m", merge_msg])

    # 9. Push to remote
    if push:
        print(f"[Deliver] Pushing {target_branch} to origin/{target_branch}...")
        _run_cmd(["git", "push", "origin", target_branch])

    # 10. Record delivery provenance
    merge_sha = _run_cmd(["git", "rev-parse", "HEAD"]).stdout.strip()[:8]
    print(f"[Deliver] Recording delivery provenance on {item_id} (merge_sha={merge_sha}, branch={cur_branch})...")
    backlog.set_delivery(scope, project, item_id, branch=cur_branch, merge_sha=merge_sha)

    # Re-export item JSON with delivery link
    it_delivered = backlog.get_epic(scope, project, item_id)
    if it_delivered and item_json_path.parent.exists():
        with open(item_json_path, "w", encoding="utf-8") as f:
            f.write(json.dumps(it_delivered, indent=2, ensure_ascii=False) + "\n")

    # 11. Clean up local feature branch
    if delete_branch:
        print(f"[Deliver] Cleaning up local feature branch {cur_branch}...")
        _run_cmd(["git", "branch", "-d", cur_branch], check=False)

    print(f"[Deliver] SUCCESS: {item_id} delivered and merged to {target_branch} ({merge_sha}).")
    return {
        "ok": True,
        "item": item_id,
        "branch": cur_branch,
        "target": target_branch,
        "merge_sha": merge_sha
    }


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Deliver backlog item(s) (BI-PF-0421 / BI-PF-1549)")
    ap.add_argument("--item", default="", help="Plane A: deliver a specific completed item from current branch")
    ap.add_argument("--scope", default="product_forge")
    ap.add_argument("--project", default="")
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--no-push", action="store_true", help="Plane A: skip pushing to origin")
    ap.add_argument("--no-delete-branch", action="store_true", help="Plane A: keep local feature branch")
    a = ap.parse_args(argv)

    if a.item:
        try:
            res = deliver_plane_a(
                a.item, scope=a.scope, project=a.project or None,
                push=not a.no_push, delete_branch=not a.no_delete_branch
            )
            print(json.dumps(res, indent=2))
            return 0
        except Exception as e:
            print(f"[Deliver] ERROR: {e}", file=sys.stderr)
            return 1

    from core import delivery
    res = delivery.drain(a.scope, a.project or None, limit=a.limit)
    print(json.dumps(res, indent=2))
    return 0 if all(d.get("ok") for d in res.get("delivered", [])) else 1


if __name__ == "__main__":
    raise SystemExit(main())
