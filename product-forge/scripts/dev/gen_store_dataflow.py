"""EDP-02 (BI-PF-1294): generate ``docs/STORE-DATAFLOW.md`` from ``config/store-registry.json``.

Single reader of the registry for the data-flow inventory; do not hand-edit the output.
Usage: ``python scripts/dev/gen_store_dataflow.py`` (write) | ``--check`` (freshness gate).
"""
import json
import os
import sys

try:
    from core.paths import ROOT
except ImportError:
    ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))

KEYS = ("sensitivity", "tenant_scope", "backend", "retention", "recovery_tier", "migration_status")
_OUT = os.path.join(ROOT, "docs", "STORE-DATAFLOW.md")


def _registry():
    with open(os.path.join(ROOT, "config", "store-registry.json"), encoding="utf-8") as f:
        return json.load(f)


def build() -> str:
    reg = _registry()
    stores = reg.get("stores", {}) or {}
    defaults = reg.get("classification_defaults", {}) or {}
    lines = [
        "# Store Data-Flow Inventory",
        "",
        "Generated by `scripts/dev/gen_store_dataflow.py` from `config/store-registry.json` "
        "(EDP-02 / BI-PF-1294). Do not edit by hand.",
        "",
        f"Stores: {len(stores)}. Classification baseline (`classification_defaults`) + per-store overrides.",
        "",
        "| store | owner | kind | scope | visibility | " + " | ".join(KEYS) + " |",
        "|---|---|---|---|---|" + "---|" * len(KEYS),
    ]
    for name in sorted(stores):
        m = stores[name] or {}
        eff = dict(defaults)
        eff.update(m.get("classification") or {})
        row = [name, m.get("owner", ""), m.get("kind", ""), m.get("scope", ""), m.get("visibility", "")]
        row += [str(eff.get(k, "")) for k in KEYS]
        lines.append("| " + " | ".join(row) + " |")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    content = build()
    if "--check" in sys.argv:
        cur = open(_OUT, encoding="utf-8").read() if os.path.exists(_OUT) else ""
        if cur != content:
            print("[FAIL] docs/STORE-DATAFLOW.md is stale (run: python scripts/dev/gen_store_dataflow.py)")
            return 1
        print("store-dataflow: OK (fresh)")
        return 0
    with open(_OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)
    print(f"wrote docs/STORE-DATAFLOW.md ({len(_registry().get('stores', {}))} stores)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
