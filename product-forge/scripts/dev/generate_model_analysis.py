def fetch_or_models():
    data = _get("https://openrouter.ai/api/v1/models", "OPENROUTER_API_KEY")
    return data.get("data", [])


def fetch_zen_models():
    data = _get("https://opencode.ai/zen/v1/models", "OPENCODE_ZEN_API_KEY")
    return [m.get("id") for m in data.get("data", [])]


def caps_from_registry(m):
    return {c for c in (m.get("capabilities") or [])}


def or_params(m):
    params = set(m.get("supported_parameters") or [])
    arch = m.get("architecture") or {}
    modal = set(arch.get("input_modalities") or [])
    return params, modal


def fmt_cost(a, b):
    if a is None:
        return "?"
    if a == 0 and b == 0:
        return "free"
    return f"${a}/${b}"


