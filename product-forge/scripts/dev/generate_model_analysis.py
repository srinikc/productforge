def _get(url, key_env=""):
    headers = {"User-Agent": "model-analysis/1.0"}
    if key_env:
        k = os.getenv(key_env, "")
        if k:
            headers["Authorization"] = "Bearer " + k
    req = urllib.request.Request(url, headers=headers)
    try:
        with urllib.request.urlopen(req, timeout=60) as r:
            return json.loads(r.read().decode())
    except Exception as e:
        print("fetch failed", url, e)
        return {}


def load_registry():
    if os.path.exists(REGISTRY):
        return json.load(open(REGISTRY, encoding="utf-8")).get("models", [])
    return []


def load_agents():
    agents = []
    for f in sorted(glob.glob(os.path.join(ROOT, "agents", "*.agent.json"))):
        try:
            d = json.load(open(f, encoding="utf-8"))
        except Exception:
            continue
        agents.append({
            "id": d.get("id") or os.path.basename(f).replace(".agent.json", ""),
            "tools": d.get("tools") or [],
            "desc": (d.get("description") or "").strip(),
        })
    return agents


