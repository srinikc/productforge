"""
Playwright MCP Integration - AI-driven visual test generation using Playwright MCP server
"""

import json
import subprocess
from typing import Dict, List, Any, Optional
from pathlib import Path

class PlaywrightMCP:
    """Integration with Playwright MCP server for visual test generation"""
    
    def __init__(self):
        self.mcp_server_running = False
        self.screenshots_path = Path("screenshots")
        self.screenshots_path.mkdir(exist_ok=True)
    
    def start_mcp_server(self) -> bool:
        """Start Playwright MCP server"""
        try:
            # Check if Playwright is installed
            result = subprocess.run(
                ["npx", "@anthropic-ai/playwright-mcp", "--help"],
                capture_output=True,
                text=True
            )
            if result.returncode == 0:
                self.mcp_server_running = True
                return True
        except:
            pass
        return False
    
    def generate_visual_tests_from_urls(self, urls: List[Dict[str, str]], 
                                        feature_id: str) -> str:
        """Generate visual regression tests from URLs"""
        
        test_code = '''"""
Visual Regression Tests - Auto-generated by Playwright MCP
Feature: {feature_id}
"""

import pytest
from playwright.sync_api import Page, expect

pytestmark = [pytest.mark.visual, pytest.mark.{feature_id}]

class Test{feature_id.title()}Visual:
    """Visual regression tests"""
'''.format(feature_id=feature_id)
        
        for url_info in urls:
            page_name = url_info.get("name", "page")
            url = url_info.get("url", "/")
            selector = url_info.get("main_selector", "body")
            
            test_code += f'''
    def test_{page_name}_visual_baseline(self, page: Page):
        """Capture {page_name} baseline screenshot"""
        page.goto("{url}")
        page.wait_for_load_state("networkidle")
        page.screenshot(path="screenshots/{feature_id}_{page_name}_baseline.png", full_page=True)
    
    def test_{page_name}_visual_regression(self, page: Page):
        """Compare {page_name} against baseline"""
        page.goto("{url}")
        page.wait_for_load_state("networkidle")
        expect(page).to_have_screenshot("screenshots/{feature_id}_{page_name}_baseline.png")
    
    def test_{page_name}_responsive_mobile(self, page: Page):
        """Test {page_name} mobile viewport"""
        page.goto("{url}")
        page.set_viewport_size({{"width": 375, "height": 667}})
        page.wait_for_load_state("networkidle")
        page.screenshot(path="screenshots/{feature_id}_{page_name}_mobile.png", full_page=True)
    
    def test_{page_name}_responsive_tablet(self, page: Page):
        """Test {page_name} tablet viewport"""
        page.goto("{url}")
        page.set_viewport_size({{"width": 768, "height": 1024}})
        page.wait_for_load_state("networkidle")
        page.screenshot(path="screenshots/{feature_id}_{page_name}_tablet.png", full_page=True)
'''
        
        return test_code
    
    def generate_interactive_tests(self, flows: List[Dict[str, Any]], 
                                   feature_id: str) -> str:
        """Generate interactive E2E tests from user flows"""
        
        test_code = '''"""
Interactive E2E Tests - Auto-generated by Playwright MCP
Feature: {feature_id}
"""

import pytest
from playwright.sync_api import Page, expect

pytestmark = [pytest.mark.e2e, pytest.mark.visual, pytest.mark.{feature_id}]

class Test{feature_id.title()}Interactive:
    """Interactive E2E tests with visual verification"""
'''.format(feature_id=feature_id)
        
        for flow in flows:
            flow_name = flow.get("name", "flow")
            steps = flow.get("steps", [])
            
            steps_code = ""
            for i, step in enumerate(steps):
                action = step.get("action", "wait")
                
                if action == "navigate":
                    steps_code += f'        page.goto("{step.get("url", "/")}")\n'
                    steps_code += f'        page.wait_for_load_state("networkidle")\n'
                elif action == "click":
                    steps_code += f'        page.click("{step.get("selector", "")}")\n'
                elif action == "fill":
                    steps_code += f'        page.fill("{step.get("selector", "")}", "{step.get("value", "")}")\n'
                elif action == "screenshot":
                    name = step.get("name", f"step_{i}")
                    steps_code += f'        page.screenshot(path="screenshots/{feature_id}_{flow_name}_{name}.png")\n'
                elif action == "assert_visible":
                    steps_code += f'        expect(page.locator("{step.get("selector", "")}")).to_be_visible()\n'
            
            test_code += f'''
    def test_{flow_name}(self, page: Page):
        """Test {flow_name} user flow"""
{steps_code}
        # Final screenshot
        page.screenshot(path="screenshots/{feature_id}_{flow_name}_final.png")
'''
        
        return test_code
    
